// ============================================
// User — מודל המשתמשת
// ============================================
// זה המודל הבסיסי של המערכת. כל שאר המודלים
// מצביעים עליו: מוצר שייך למוכרת, הזמנה שייכת
// לקונה ולמוכרת, מועדף שייך למשתמשת.
// ============================================

const mongoose = require('mongoose');

const userSchema = new mongoose.Schema({

  name: {
    type: String,
    required: true,
    // trim מוריד רווחים מההתחלה ומהסוף.
    // בלי זה " רבקי " ו-"רבקי" הם שני שמות שונים.
    trim: true
  },

  email: {
    type: String,
    required: true,

    // unique יוצר אינדקס ייחודי במונגו — ברמת מסד הנתונים,
    // לא ברמת הקוד. גם אם שתי הרשמות יגיעו בדיוק באותו רגע,
    // רק אחת תיכנס והשנייה תיפול עם שגיאת duplicate key.
    // בקוד יש בדיקה נוספת (findOne) שמחזירה הודעה יפה,
    // אבל ההגנה האמיתית היא כאן.
    unique: true,

    // lowercase ממיר לאותיות קטנות לפני השמירה.
    // Rivki@Gmail.com ו-rivki@gmail.com הם אותה כתובת,
    // ובלי זה אפשר היה להירשם פעמיים עם אותו מייל.
    lowercase: true,
    trim: true
  },

  password: {
    type: String,
    required: true,

    // אורך מינימלי — אבל שימו לב: הבדיקה הזו רצה על
    // הסיסמה המוצפנת, שתמיד ארוכה מ-6. הוולידציה האמיתית
    // של 6 תווים נמצאת ב-auth.js בצד הלקוח.
    minlength: 6,

    // ⭐ select: false — השדה לא נשלף בשאילתות רגילות.
    // כל User.find() או User.findById() יחזיר משתמשת
    // בלי שדה password בכלל, גם אם נשכח לסנן.
    // זו הגנה בברירת מחדל: אי אפשר להדליף סיסמה בטעות.
    //
    // המקום היחיד שצריך אותה הוא בהתחברות, ושם מבקשים
    // אותה במפורש: .select('+password')
    select: false
  },

  role: {
    type: String,

    // enum מגביל לשני ערכים בלבד. אם מישהו ינסה לשלוח
    // role: 'superadmin' — Mongoose יזרוק שגיאת ולידציה.
    enum: ['user', 'admin'],

    // ⭐ ברירת המחדל היא user, לא admin.
    // זה קריטי: register לא מקבל role מהלקוח בכלל,
    // ולכן כל מי שנרשמת מקבלת הרשאות רגילות.
    // אי אפשר להירשם כמנהלת — רק מנהלת קיימת
    // יכולה לשדרג דרך changeRole.
    default: 'user'
  },

  points: {
    type: Number,
    default: 0,

    // min: 0 — מונע יתרה שלילית.
    // גם אם באג בקוד ינסה להוריד יותר נקודות ממה שיש,
    // מונגו יסרב. זו רשת ביטחון מתחת ללוגיקה
    // של createOrder שכבר בודקת $gte.
    min: 0
  },

  city: {
    type: String,
    trim: true
    // לא required במודל, אבל כן נדרש ב-register.
    // הסיבה: משתמשות ישנות מה-seed עשויות להיות בלי עיר,
    // ולא רוצים שהמודל ייפול עליהן.
  },

  phone: {
    type: String,
    trim: true

    // ⭐ למה String ולא Number?
    // מספר טלפון מתחיל ב-0, ו-Number היה מוחק אותו:
    // 0501234567 היה הופך ל-501234567.
    // חוץ מזה אף פעם לא עושים חשבון על טלפון.
  },

  avatar: {
    type: String
    // כתובת תמונה. כרגע לא בשימוש — בפרופיל מוצגת
    // האות הראשונה של השם במקום.
  }

}, {
  // ⭐ timestamps מוסיף אוטומטית שני שדות:
  // createdAt — מתי נוצרה
  // updatedAt — מתי עודכנה לאחרונה
  //
  // createdAt הוא מה שמאפשר למיין משתמשות
  // מהחדשה לישנה בדשבורד, ומה שמזין את ה-Aggregate
  // של מכירות לפי חודש (על מודל ההזמנות).
  timestamps: true
});

module.exports = mongoose.model('User', userSchema);