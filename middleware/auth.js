// ============================================
// middleware/auth.js — שומרת הסף של ה-API
// ============================================
// שתי פונקציות שרצות לפני הקונטרולרים:
//
//   auth    — מי את? (אימות / Authentication)
//   isAdmin — מה מותר לך? (הרשאה / Authorization)
//
// זו הפרדה חשובה: אימות קובע מי המשתמשת,
// הרשאה קובעת מה היא רשאית לעשות.
// ============================================

const jwt = require('jsonwebtoken');


// ============================================
// auth — מאמתת את הטוקן
// ============================================
// ⭐ מה זה middleware בכלל?
// פונקציה שרצה *באמצע* — בין הבקשה שהגיעה
// לבין הקונטרולר שמטפל בה. היא מקבלת שלושה
// פרמטרים: req, res ו-next.
//
// יש לה שתי אפשרויות:
//   לעצור את הבקשה     → res.status(...).json(...)
//   להעביר אותה הלאה   → next()
//
// כל עוד לא קראו ל-next(), הקונטרולר לא ירוץ.
function auth(req, res, next) {

  // ============================================
  // שלב 1 — שולפים את הטוקן מהכותרת
  // ============================================
  // הדפדפן שולח כותרת בפורמט הזה:
  //   Authorization: Bearer eyJhbGciOiJIUzI1NiIs...
  //
  // split(' ') מפצל לשני חלקים לפי הרווח:
  //   [0] = "Bearer"   (סוג האימות, לא מעניין אותנו)
  //   [1] = הטוקן עצמו  ← זה מה שאנחנו רוצים
  //
  // ⭐ ה-?. (optional chaining) קריטי כאן:
  // אם אין כותרת Authorization בכלל, הערך הוא undefined.
  // בלי ה-?. השרת היה מנסה לקרוא ל-split על undefined
  // וקורס עם שגיאה. עם ה-?. הוא פשוט מחזיר undefined.
  const token = req.headers.authorization?.split(' ')[1];


  // ============================================
  // שלב 2 — אין טוקן = אין כניסה
  // ============================================
  // 401 Unauthorized = "אני לא יודע מי את".
  // שימו לב להבדל מ-403 למטה.
  if (!token) {
    return res.status(401).json({ message: 'Authentication required' });
  }


  // ============================================
  // שלב 3 — מאמתים את החתימה
  // ============================================
  try {

    // ⭐ מה jwt.verify עושה בפועל?
    // הטוקן בנוי משלושה חלקים מופרדים בנקודות:
    //   header.payload.signature
    //
    // ה-payload הוא פשוט Base64 — כל אחד יכול לפתוח
    // אותו ולקרוא מה כתוב שם. זה לא הצפנה!
    //
    // מה שמגן עליו זו החתימה. היא נוצרה מה-payload
    // ביחד עם ה-JWT_SECRET שלנו, שנמצא רק ב-.env
    // על השרת. verify מחשב את החתימה מחדש ומשווה.
    //
    // אם מישהו שינה ולו תו אחד ב-payload — למשל
    // החליף role: 'user' ל-role: 'admin' — החתימה
    // כבר לא תתאים, verify יזרוק שגיאה, והבקשה תיפסל.
    // בלי ה-SECRET אי אפשר לייצר חתימה חדשה תקפה.
    //
    // verify בודק גם את תאריך התפוגה (expiresIn: '7d').

    // ⭐ req.user — זו השורה שמחברת הכול.
    // מה שחוזר מ-verify הוא ה-payload: { id, role }.
    // אנחנו מצמידים אותו לאובייקט הבקשה, וכך כל
    // קונטרולר שרץ אחרי auth יכול לכתוב req.user.id
    // ולדעת מי המשתמשת — בלי שאילתה למסד.
    //
    // זה למשל מה שמאפשר ל-createProduct לכתוב
    // sellerId: req.user.id, ולא לסמוך על מה
    // שהלקוח שלח בגוף הבקשה.
    req.user = jwt.verify(token, process.env.JWT_SECRET);  // { id, role }

    // הכול תקין — מעבירים לקונטרולר
    next();

  } catch {
    // ⭐ catch בלי פרמטר — אנחנו לא צריכים את פרטי
    // השגיאה. בכוונה לא מחזירים ללקוח אם הטוקן
    // פג תוקף או שהחתימה מזויפת: מידע כזה עוזר
    // למי שמנסה לתקוף.
    res.status(401).json({ message: 'Session expired, please log in again' });
  }
}


// ============================================
// isAdmin — בודקת הרשאות
// ============================================
// ⭐ "Must run after auth" — זה לא סתם תיעוד,
// זו תלות אמיתית. הפונקציה קוראת ל-req.user.role,
// ו-req.user קיים רק אחרי ש-auth הציבה אותו.
//
// אם מישהי תכתוב router.get('/x', isAdmin, ctrl)
// בלי auth לפניו — השרת יקרוס על undefined.role.
// לכן תמיד כותבים אותן יחד: auth, isAdmin
function isAdmin(req, res, next) {

  // ⭐ למה 403 ולא 401?
  // 401 Unauthorized = "אני לא יודע מי את" (אין טוקן / פג)
  // 403 Forbidden    = "אני יודע בדיוק מי את, ואסור לך"
  //
  // ההבדל חשוב גם בצד הלקוח: ב-common.js, פונקציית api()
  // מנתקת אוטומטית כשמקבלת 401 — כי הטוקן כנראה פג.
  // על 403 היא לא מנתקת, רק מציגה הודעה. זה הגיוני:
  // משתמשת רגילה שניסתה להיכנס לדשבורד לא צריכה
  // להיזרק מהחשבון שלה.
  if (req.user.role !== 'admin') {
    return res.status(403).json({ message: 'You do not have permission for this action' });
  }

  next();
}


// מייצאים אובייקט עם שתי הפונקציות, כדי שאפשר יהיה
// לכתוב בראוטים: const { auth, isAdmin } = require(...)
module.exports = { auth, isAdmin };